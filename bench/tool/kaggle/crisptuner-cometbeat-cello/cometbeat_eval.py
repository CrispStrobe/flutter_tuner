#!/usr/bin/env python3
"""CometBeat's RMVPE and FCPE over the FULL corpora, in CometBeat's runtime.

Generated by bench/tool/kaggle/build_spectro_kernel.py — do not edit here.

§35.6 reported these two engines on prefixes and said so: FCPE on 40 of
GuitarSet's 180 solo files, RMVPE on 55 of MUSERC's 109 cello takes, and
RMVPE on GuitarSet not at all, because one 22-second file reached 3.5 GB of
resident memory in `onnx_runtime_dart` and was killed. A Kaggle worker has
memory the shared VPS did not.

Two rules this kernel does not break.

* **Nothing is chunked.** RMVPE's U-Net takes the whole recording as one
  forward pass; splitting it would make this a different engine from the one
  CometBeat ships, and measuring a different engine was the thing §35.6
  declined to do.
* **Nothing is re-implemented.** The engines are CometBeat's own Dart files
  as `tool/sync_cometbeat.sh` copies them, run by `bin/cometbeat.dart`
  through `onnx_runtime_dart` — the same runtime, the same decode, the same
  scoring code as every other row in this report. The only thing Kaggle
  changes is the machine.

`--subset N` accumulates a second table over the first N files of the SAME
pass, so §35.6's prefix and the full corpus can be compared line for line
without the confound of two different runs. That is the question §35.6 had to
leave open when it warned that `cb-pyin` moves 82.63 -> 80.45 between them.
"""

import os
import subprocess
import sys
import urllib.request
import zipfile

WORK = "/kaggle/working"
DATA = os.path.join(WORK, "datasets")
DART = os.path.join(WORK, "dart-sdk", "bin", "dart")
DART_URL = ("https://storage.googleapis.com/dart-archive/channels/stable/"
            "release/3.13.4/sdk/dartsdk-linux-x64-release.zip")
REPO = "https://github.com/CrispStrobe/flutter_tuner.git"
REF = "bench/kaggle-four-models"
CORPUS = "cello"
ENGINES = "cb-rmvpe,cb-fcpe"
SUBSET = "55"


def sh(cmd, **kw):
    print(f"$ {cmd}", flush=True)
    subprocess.run(cmd, shell=True, check=True, **kw)


def require_internet():
    try:
        urllib.request.urlopen("https://zenodo.org", timeout=30).close()
    except Exception as exc:  # noqa: BLE001
        raise SystemExit(f"no internet on this worker ({exc}); re-run")


def models_dir():
    for p in ("/kaggle/input/crisptuner-onnx",
              "/kaggle/input/datasets/chr1s4/crisptuner-onnx"):
        if os.path.isdir(p):
            return p
    raise SystemExit("crisptuner-onnx is not attached (gotcha #13)")


def install_dart():
    if os.path.exists(DART):
        return
    zip_path = os.path.join(WORK, "dart.zip")
    urllib.request.urlretrieve(DART_URL, zip_path)
    with zipfile.ZipFile(zip_path) as z:
        z.extractall(WORK)
    os.chmod(DART, 0o755)
    for extra in ("dartaotruntime", "utils/gen_snapshot"):
        p = os.path.join(WORK, "dart-sdk", "bin", extra)
        if os.path.exists(p):
            os.chmod(p, 0o755)
    os.remove(zip_path)
    sh(f"{DART} --version")


def clone():
    """The repo at an explicit ref, with the SHA printed.

    `git push` does not update a Kaggle kernel (gotcha #24), so a kernel and
    the tree it tests can drift apart with nothing in the log looking wrong.
    Printing both the ref asked for and the SHA obtained is what makes that
    visible.
    """
    dst = os.path.join(WORK, "flutter_tuner")
    if not os.path.isdir(dst):
        sh(f"git clone --depth 1 --branch {REF} {REPO} {dst}")
    sha = subprocess.run(["git", "-C", dst, "rev-parse", "HEAD"],
                         capture_output=True, text=True).stdout.strip()
    print(f"cloned {REF} at {sha}", flush=True)
    return dst


def fetch_guitarset():
    """GuitarSet (Zenodo 3371780, CC BY 4.0): annotations + mono-mic audio."""
    audio, ann = os.path.join(DATA, "audio"), os.path.join(DATA, "annotation")
    if os.path.isdir(audio) and len(os.listdir(audio)) > 100:
        return
    os.makedirs(DATA, exist_ok=True)
    for name, url in [
        ("annotation.zip",
         "https://zenodo.org/records/3371780/files/annotation.zip?download=1"),
        ("audio_mono-mic.zip",
         "https://zenodo.org/records/3371780/files/audio_mono-mic.zip?download=1"),
    ]:
        target = os.path.join(DATA, name)
        print(f"fetching {name}", flush=True)
        urllib.request.urlretrieve(url, target)
        out = ann if "annotation" in name else audio
        os.makedirs(out, exist_ok=True)
        with zipfile.ZipFile(target) as z:
            z.extractall(out)
        os.remove(target)
    print(f"audio {len(os.listdir(audio))}, annotations {len(os.listdir(ann))}",
          flush=True)


def fetch_muserc():
    """MUSERC (Zenodo 1560651, CC BY 4.0). Only `SA/` — 72 MB of the 1.4 GB."""
    sa = os.path.join(DATA, "muserc", "MUSERC", "SA")
    if os.path.isdir(sa) and len(os.listdir(sa)) > 100:
        return
    root = os.path.join(DATA, "muserc")
    os.makedirs(root, exist_ok=True)
    target = os.path.join(root, "MUSERC.zip")
    print("fetching MUSERC (1.4 GB)", flush=True)
    urllib.request.urlretrieve(
        "https://zenodo.org/records/1560651/files/MUSERC.zip?download=1", target)
    with zipfile.ZipFile(target) as z:
        for name in z.namelist():
            if name.startswith("MUSERC/SA/") and not name.startswith("__MACOSX"):
                z.extract(name, root)
    os.remove(target)
    print(f"takes: {len(os.listdir(sa))}", flush=True)


require_internet()
install_dart()
repo = clone()
models = models_dir()
if CORPUS == "guitar":
    fetch_guitarset()
else:
    fetch_muserc()

bench = os.path.join(repo, "bench")
sh(f"{DART} pub get", cwd=bench)
print(f"\nfree memory before the run:", flush=True)
sh("free -g || true")

# `--models` is the mounted dataset: rmvpe.onnx, fcpe.onnx and the two mel
# assets sit flat in it, which is the layout `loadNeural` expects.
cmd = (f"{DART} run bin/cometbeat.dart --corpus {CORPUS} --data {DATA} "
       f"--models {models} --engines {ENGINES} --subset {SUBSET}")
# Not check=True: an OOM kill part-way through is a RESULT here, not a
# harness failure, and the per-file progress lines say exactly how far the
# run got. Swallowing the exit code would be wrong; hiding the log would be
# worse.
print(f"$ {cmd}", flush=True)
rc = subprocess.run(cmd, shell=True, cwd=bench).returncode
print(f"\ncometbeat.dart exited {rc}", flush=True)
sh("free -g || true")
if rc != 0:
    print("NON-ZERO EXIT: if this is 137 the kernel OOM-killed it, and the "
          "last progress line above is the file it died on.", flush=True)
