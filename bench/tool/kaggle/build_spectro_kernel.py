def build_spectro():
    target = os.path.join(HERE, "spectro-eval")
    os.makedirs(target, exist_ok=True)
    body = "".join([
        SPECTRO_PREAMBLE.replace("{account}", ACCOUNT),
        strip_module(os.path.join(TOOL, "spectro_reference.py"),
                     drop_from="\ndef main():"),
        "\n\n",
        strip_module(os.path.join(TOOL, "spectro_notes.py"),
                     rename_main="main_notes"),
        "\n\n",
        strip_module(os.path.join(TOOL, "onnx_timing.py"),
                     rename_main="main_timing"),
        SPECTRO_DRIVER,
    ])
    # The evaluators import each other by module name when run locally; in
    # one concatenated file those imports would fail, and dropping them is
    # safe precisely because the imported names are defined above.
    body = body.replace(
        "from spectro_reference import mel, resample, sigmoid\n",
        "# (spectro_reference is inlined above)\n")
    body = body.replace("    from spectro_reference import mel\n", "")
    body = body.replace("    from spectro_reference import resample\n", "")
    with open(os.path.join(target, "spectro_eval.py"), "w") as f:
        f.write(body)
    meta = {
        "id": f"{ACCOUNT}/crisptuner-spectro-eval",
        "title": "CrispTuner spectro eval",
        "code_file": "spectro_eval.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_internet": "true",
        "competition_sources": [],
        "dataset_sources": [MODEL_DATASET],
        "kernel_sources": [],
        "model_sources": [],
    }
    with open(os.path.join(target, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=1)
    print("wrote", target)


