#!/usr/bin/env python3
"""Regenerate the Kaggle kernels that run the four models §35 could not
finish measuring on the VPS.

    python3 tool/kaggle/build_spectro_kernel.py
    cd tool/kaggle/spectro-eval && python -m kaggle kernels push -p .
    cd ../cometbeat-full && python -m kaggle kernels push -p .

Same rule as `build_kernel.py`, for the same reason: **a Kaggle script kernel
uploads only its `code_file`** (kaggle-usage.md gotcha #3), so a kernel has to
be one self-contained file. Rather than maintain a second copy of any
evaluation, each kernel is generated by concatenating a Kaggle preamble with
the local evaluators, verbatim, and everything a worker needs that is not in
the script arrives via `dataset_sources`.

Three kernels come out of here.

* **spectro-eval** (Python) reproduces §35.3's MusicNet note-level table on a
  machine that is not shared, and answers the two questions §35 left open
  about cost: native-ORT throughput at 1/2/4 intra-op threads, and peak RSS,
  for all four models. The accuracy half is a genuine second opinion — the
  decoders are `tool/spectro_notes.py`'s numpy ports and the metric is
  `mir_eval` itself, where §35.3 used `lib/hft.dart` / `lib/oaf.dart` and
  `lib/note_metrics.dart`.
* **cometbeat-guitar** and **cometbeat-cello** (Dart) run CometBeat's own
  RMVPE and FCPE engines, in CometBeat's own runtime, over the FULL corpora.
  §35.6 could report RMVPE on GuitarSet not at all (one 22-second file
  reached 3.5 GB in `onnx_runtime_dart` and was OOM-killed) and FCPE on 40 of
  180 files; a Kaggle worker has the memory the VPS did not. **Nothing is
  chunked.** Chunking RMVPE's input would make it a different engine from the
  one CometBeat ships, which is exactly why §35.6 declined to do it.

The corpora are fetched from Zenodo inside each kernel. None of them is
mirrored as a Kaggle dataset: CLAUDE.md's licence note is that these corpora
are for local evaluation and must never be redistributed.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.dirname(os.path.dirname(HERE))
TOOL = os.path.join(BENCH, "tool")

# The Kaggle account that owns the private model dataset. Private datasets are
# per-account (gotcha #13): the dataset and the kernel must be the same
# account, or the attachment silently fails as "not valid dataset sources".
ACCOUNT = "chr1s4"
MODEL_DATASET = f"{ACCOUNT}/crisptuner-onnx"
DART_VERSION = "3.13.4"
# Pin the branch the Dart kernels clone. `git push` does NOT update a Kaggle
# kernel and a kernel that clones `main` would silently score a different
# tree from the one under review (gotcha #24), so the ref is explicit and the
# kernel prints the SHA it actually got.
REPO = "https://github.com/CrispStrobe/flutter_tuner.git"
REPO_REF = "bench/kaggle-four-models"


def strip_module(path, drop_from=None, rename_main=None):
    """One local tool's source, ready to be concatenated with another.

    Everything above the first `import` is the module docstring, which is
    kept — it is where the reasoning lives and a kernel log is a bad place to
    lose it. `if __name__ == "__main__"` is dropped because the kernel has
    one entry point, and `main` is renamed because two evaluators in one file
    would otherwise shadow each other. That renaming is the only edit made to
    any evaluator on the way to Kaggle.
    """
    src = open(path).read()
    if drop_from and drop_from in src:
        src = src[:src.index(drop_from)]
    src = src.split('if __name__ == "__main__":')[0]
    if rename_main:
        src = src.replace("\ndef main():", f"\ndef {rename_main}():")
    return src.rstrip() + "\n"


